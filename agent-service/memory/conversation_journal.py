"""Fenced executions and authoritative conversation commits in PostgreSQL."""
import asyncio
import json
import uuid
from contextlib import asynccontextmanager

from core.state import AgentError

DB_NOW = "EXTRACT(EPOCH FROM clock_timestamp())::double precision"
MAX_TURNS = 8


def encoded(value):
    from memory.task_store import dump
    return dump(value)


class ConversationJournal:
    def _migrate_conversations(self, conn):
        conn.execute("ALTER TABLE agent_tasks ADD COLUMN IF NOT EXISTS execution_epoch BIGINT NOT NULL DEFAULT 0")
        conn.execute("""CREATE TABLE IF NOT EXISTS agent_conversations (
            scope TEXT NOT NULL,session_id TEXT NOT NULL,revision BIGINT NOT NULL DEFAULT 0,
            active_task_id TEXT,PRIMARY KEY(scope,session_id))""")
        conn.execute("""CREATE TABLE IF NOT EXISTS agent_turns (
            task_id TEXT PRIMARY KEY REFERENCES agent_tasks(id),scope TEXT NOT NULL,session_id TEXT NOT NULL,
            ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY,data TEXT NOT NULL,updated DOUBLE PRECISION NOT NULL)""")
        conn.execute("CREATE INDEX IF NOT EXISTS agent_turn_session ON agent_turns(scope,session_id,ordinal)")
        conn.execute("""CREATE TABLE IF NOT EXISTS agent_session_cache_outbox (
            scope TEXT NOT NULL,session_id TEXT NOT NULL,revision BIGINT NOT NULL,
            owner TEXT,lease_until DOUBLE PRECISION NOT NULL DEFAULT 0,attempts INTEGER NOT NULL DEFAULT 0,
            next_attempt DOUBLE PRECISION NOT NULL DEFAULT 0,PRIMARY KEY(scope,session_id))""")
        conn.execute("INSERT INTO agent_conversations(scope,session_id) SELECT DISTINCT scope,session_id FROM agent_tasks ON CONFLICT DO NOTHING")
        self._backfill_turns(conn)
        conn.execute("INSERT INTO agent_schema_version(version) VALUES(3) ON CONFLICT DO NOTHING")

    def _backfill_turns(self, conn, scope=None, session=None):
        params = () if scope is None else (scope, session)
        where = "" if scope is None else " AND scope=%s AND session_id=%s"
        # Legacy tasks already contain committed answers. Import only these,
        # never an uncommitted Redis snapshot or a running executor's local history.
        conn.execute(f"""INSERT INTO agent_turns(task_id,scope,session_id,data,updated)
            SELECT id,scope,session_id,jsonb_strip_nulls(jsonb_build_object(
                'task_id',id,'user',request::jsonb->>'message','assistant',output::jsonb->>'answer',
                'trace',COALESCE(output::jsonb->'trace','[]'::jsonb),'constraints',output::jsonb->'constraints',
                'state',output::jsonb->'state','decision_context',output::jsonb->'decision_context'))::text,updated
            FROM agent_tasks WHERE output IS NOT NULL AND output::jsonb ? 'answer'{where}
            ORDER BY created,id ON CONFLICT(task_id) DO NOTHING""", params)
        conn.execute("""UPDATE agent_conversations c SET revision=GREATEST(c.revision,t.n)
            FROM (SELECT scope,session_id,COUNT(*) AS n FROM agent_turns GROUP BY scope,session_id) t
            WHERE c.scope=t.scope AND c.session_id=t.session_id""")
        conn.execute("""INSERT INTO agent_session_cache_outbox(scope,session_id,revision)
            SELECT scope,session_id,revision FROM agent_conversations WHERE revision>0
            ON CONFLICT(scope,session_id) DO NOTHING""")

    def _conversation(self, conn, scope, session, *, create=False, lock=False):
        row = conn.execute("SELECT * FROM agent_conversations WHERE scope=%s AND session_id=%s" +
                           (" FOR UPDATE" if lock else ""), (scope, session)).fetchone()
        if row is None:
            exists = conn.execute("SELECT id FROM agent_tasks WHERE scope=%s AND session_id=%s LIMIT 1", (scope, session)).fetchone()
            if not create and not exists:
                raise AgentError('SESSION_NOT_FOUND', '对话不存在或不属于当前用户', 404)
            conn.execute("INSERT INTO agent_conversations(scope,session_id) VALUES(%s,%s) ON CONFLICT DO NOTHING", (scope, session))
            if exists:
                self._backfill_turns(conn, scope, session)
            row = conn.execute("SELECT * FROM agent_conversations WHERE scope=%s AND session_id=%s" +
                               (" FOR UPDATE" if lock else ""), (scope, session)).fetchone()
        return row

    def _history(self, conn, scope, session):
        rows = conn.execute("SELECT data FROM agent_turns WHERE scope=%s AND session_id=%s ORDER BY ordinal DESC LIMIT %s",
                            (scope, session, MAX_TURNS)).fetchall()
        return [json.loads(row['data']) for row in reversed(rows)]

    async def conversation_snapshot(self, scope, session, *, create=False):
        def read(conn):
            # Lock just for a consistent revision/history snapshot, never across HTTP.
            row = self._conversation(conn, scope, session, create=create, lock=True)
            return {'revision': row['revision'], 'turns': self._history(conn, scope, session)}
        return await self.call(read)

    async def conversation_revision(self, scope, session):
        return await self.call(lambda c: self._conversation(c, scope, session)['revision'])

    def execution(self, task_id):
        return (self._leases.get() or {}).get(task_id)

    async def renew(self, task_id):
        lease = self.execution(task_id)
        if not lease:
            raise AgentError('TASK_LEASE_LOST', '任务执行权已失效', 409)
        def extend(conn):
            if lease.get('job_owner'):
                changed = conn.execute(f"UPDATE agent_jobs SET lease_until={DB_NOW}+%s WHERE task_id=%s "
                    f"AND owner=%s AND state='running' AND lease_until>{DB_NOW}",
                    (lease['seconds'] + 20, task_id, lease['job_owner'])).rowcount
                if not changed:
                    raise AgentError('TASK_LEASE_LOST', '队列执行权已失效', 409)
            changed = conn.execute(f"UPDATE agent_tasks SET lease_until={DB_NOW}+%s WHERE id=%s "
                f"AND lease_owner=%s AND execution_epoch=%s AND state='running' AND lease_until>{DB_NOW}",
                (lease['seconds'], task_id, lease['owner'], lease['epoch'])).rowcount
            if not changed:
                raise AgentError('TASK_LEASE_LOST', '任务租约已过期或被接管', 409)
        await self.call(extend)

    @asynccontextmanager
    async def keep_lease(self, task_id):
        lease = self.execution(task_id)
        parent = asyncio.current_task()
        lost = []
        async def heartbeat():
            try:
                while True:
                    await asyncio.sleep(min(10, lease['seconds'] / 3))
                    await self.renew(task_id)
            except asyncio.CancelledError:
                raise
            except Exception as exc:
                lost.append(exc)
                parent.cancel()
        beat = asyncio.create_task(heartbeat())
        try:
            yield
        except asyncio.CancelledError:
            if lost:
                raise AgentError('TASK_LEASE_LOST', '无法续租，本轮停止执行', 409) from lost[0]
            raise
        finally:
            beat.cancel()
            await asyncio.gather(beat, return_exceptions=True)

    async def claim_cache_updates(self, limit=16):
        token = str(uuid.uuid4())
        def claim(conn):
            rows = conn.execute(f"SELECT scope,session_id FROM agent_session_cache_outbox WHERE next_attempt<={DB_NOW} "
                f"AND lease_until<={DB_NOW} ORDER BY next_attempt FOR UPDATE SKIP LOCKED LIMIT %s", (limit,)).fetchall()
            for row in rows:
                conn.execute(f"UPDATE agent_session_cache_outbox SET owner=%s,lease_until={DB_NOW}+15 "
                    "WHERE scope=%s AND session_id=%s", (token, row['scope'], row['session_id']))
                row['owner'] = token
            return rows
        return await self.call(claim)

    async def acknowledge_cache(self, job, revision):
        def ack(conn):
            conn.execute("DELETE FROM agent_session_cache_outbox WHERE scope=%s AND session_id=%s AND owner=%s AND revision<=%s",
                         (job['scope'], job['session_id'], job['owner'], revision))
            # A new turn may have advanced revision while this cache write ran.
            conn.execute(f"UPDATE agent_session_cache_outbox SET owner=NULL,lease_until=0,next_attempt={DB_NOW} "
                "WHERE scope=%s AND session_id=%s AND owner=%s", (job['scope'], job['session_id'], job['owner']))
        await self.call(ack)

    async def retry_cache(self, job):
        await self.call(lambda c: c.execute(f"UPDATE agent_session_cache_outbox SET owner=NULL,lease_until=0,attempts=attempts+1,"
            f"next_attempt={DB_NOW}+LEAST(60,power(2,LEAST(attempts,5))) WHERE scope=%s AND session_id=%s AND owner=%s",
            (job['scope'], job['session_id'], job['owner'])))
