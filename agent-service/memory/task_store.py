DB_NOW = "EXTRACT(EPOCH FROM clock_timestamp())::double precision"


def sanitized(value):
    if isinstance(value, dict):
        return {k: sanitized(v) for k, v in value.items()
                if k.lower() not in {"authorization", "api_key", "password", "confirmation_token"}}
    if isinstance(value, list):
        return [sanitized(item) for item in value]
    if isinstance(value, str):
        return re.sub(r"sk-[A-Za-z0-9_-]{16,}", "[REDACTED]", value)
    return value


def dump(value):
    return json.dumps(sanitized(value), ensure_ascii=False, default=str)


